  pending.shift().onSuccess({ result: { statusCode: 200, mediaUrl: 'https://ugc-cdn-test.cloudwindow-route.com/path/master.m3u8?t=test' } });
  assert.equal(video.hidden, false);
  assert.match(video.getAttribute('src'), /master\.m3u8/);
  click('video-fullscreen'); key(461);
  assert.equal(document.getElementById('player').hidden, false);
  key(461);
  assert.equal(document.getElementById('player').hidden, true);
  click('item-0');
  pending.shift().onSuccess({ result: { statusCode: 200, mediaUrl: 'https://ugc-cdn-test.cloudwindow-route.com/path/master.m3u8?t=test' } });
  click('video-fullscreen');
  click('video-next');
  assert.equal(pending[0].parameters.path, '/ver/demo-2');
  assert.equal(video.hidden, true);
  assert.equal(video.getAttribute('src'), null);
  answer('<h1 class="anime-title">Demo 2</h1><div class="episodes-nav"><a href="/ver/demo-1">Episodio anterior</a><a href="/anime/demo">Listado</a><a href="#">Episodio siguiente</a></div><script>var videos = [["Voe","https://voe.sx/e/second"]];</script>');
  assert.equal(pending.length, 0);
  assert.equal(document.getElementById('player').hidden, true);
  click('item-0');
  assert.equal(pending[0].method, 'probeProvider');
  pending.shift().onSuccess({ result: { statusCode: 200, mediaUrl: 'https://ugc-cdn-test.cloudwindow-route.com/path/master.m3u8?t=second' } });
  assert.equal(document.getElementById('player-title').textContent, 'Demo 2');
  assert.equal(document.getElementById('video-next').disabled, true);
  assert.equal(document.getElementById('player').classList.contains('video-expanded'), false);
  assert.equal(document.getElementById('player-next'), null);
  assert.equal(document.getElementById('player-episodes'), null);
  assert.equal(document.getElementById('video-previous').disabled, false);
  click('video-previous');
  assert.equal(pending[0].parameters.path, '/ver/demo-1');
  answer('<h1 class="anime-title">Demo 1</h1><div class="episodes-nav"><a href="/anime/demo">Listado</a><a href="/ver/demo-2">Episodio siguiente</a></div><script>var videos = [["Voe","https://voe.sx/e/example"]];</script>');
  assert.equal(pending.length, 0);
  assert.equal(document.getElementById('player').hidden, true);
  click('episode-list');
  assert.equal(pending[0].parameters.path, '/anime/demo');
  assert.equal(video.hidden, true);
  const detail = '<article class="anime-single"><h1 class="title">Demo</h1></article><script>var anime_info = ["10","demo","Demo"]; var episodes = [2,1];</script>';
  answer(detail);
  click('recent');
  assert.match(document.getElementById('item-0').textContent, /Episodio 2/);
  click('recent-catalog-0');
  assert.equal(pending[0].parameters.path, '/anime/demo');
  answer(detail);
  assert.match(document.getElementById('continue-anime').textContent, /Episodio 2/);
  click('item-0');
  answer('<h1 class="anime-title">Demo 2</h1><div class="episodes-nav"><a href="/anime/demo">Listado</a></div><script>var videos = [["Okru","https://ok.ru/videoembed/123"]];</script>');
  click('item-0');
  assert.equal(pending[0].parameters.url, 'https://ok.ru/videoembed/123');
  pending.shift().onSuccess({ result: { statusCode: 200, mediaUrl: 'https://vd123.okcdn.ru/?id=test' } });
  assert.equal(video.hidden, false);
  assert.equal(video.getAttribute('src'), 'https://vd123.okcdn.ru/?id=test');
  click('close-player');
  click('episode-list');
  const related = detail + '<section class="w-history"><article class="anime"><a href="/anime/related"><img src="/uploads/portadas/11.jpg"></a><h3 class="title">Related</h3><span class="year">2020</span></article></section>';
