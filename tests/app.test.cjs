  const pending = [];
  const video = document.getElementById('native-video');
  video.paused = true;
  video.pause = () => { video.paused = true; };
  video.load = () => {};
  video.play = () => { video.paused = false; return Promise.resolve(); };
  const webOS = { service: { request: (uri, options) => {
    if (options.method === 'holdPlayback') { options.onSuccess({ returnValue: true }); return { cancel() {} }; }
    pending.push(options);
  } }, platformBack: () => {} };
  window.PalmSystem = {}; window.webOS = webOS;
  vm.runInNewContext(fs.readFileSync('app/main.js', 'utf8'), { window, document, webOS, DOMParser, TioCatalog, TioHistory, URL, setTimeout, clearTimeout, Error });
  function answer(html) { pending.shift().onSuccess({ html }); }
  function click(id) { document.getElementById(id).click(); }
  function key(code) { const event = new window.Event('keydown', { cancelable: true }); event.keyCode = code; document.dispatchEvent(event); }
  assert.equal(pending[0].parameters.path, '/');
  answer('<article class="episode"><a href="/ver/demo-1"><h3>Demo 1</h3></a></article>');
  assert.equal(focused.id, 'item-0');
  document.getElementById('query').focus();
  assert.equal(document.getElementById('query').hasAttribute('readonly'), true);
  key(40);
  assert.equal(focused.id, 'item-0');
  document.getElementById('query').focus(); key(13);
  assert.equal(document.getElementById('query').hasAttribute('readonly'), false);
  key(461);
  assert.equal(document.getElementById('query').hasAttribute('readonly'), true);
  click('query');
  assert.equal(document.getElementById('query').hasAttribute('readonly'), false);
  document.getElementById('item-0').focus();
