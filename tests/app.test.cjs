  click('item-0');
  assert.equal(document.getElementById('player').hidden, false);
  assert.equal(document.getElementById('frame').getAttribute('src'), 'https://video.example/embed/1');
  click('close-player');
  assert.equal(document.getElementById('frame').getAttribute('src'), 'about:blank');
  assert.equal(focused.id, 'item-0');
  click('back');
  assert.equal(pending[0].parameters.path, '/');
  answer('<article class="episode"><a href="/ver/demo-1"><h3>Demo 1</h3></a></article>');
  document.getElementById('query').value = 'one piece';
  document.getElementById('search').dispatchEvent(new window.Event('submit', { cancelable: true }));
  assert.equal(pending[0].parameters.path, '/directorio?q=one%20piece');
  pending.shift().onFailure({ errorText: 'Sin conexión' });
  assert.equal(document.getElementById('status').textContent, 'Sin conexión');
  assert.equal(document.getElementById('retry').hidden, false);
  click('retry'); answer('<h1 class="title">Resultados</h1>');
  assert.match(document.getElementById('status').textContent, /No se encontraron/);
  click('recent');
  assert.equal(pending.length, 0);
  assert.match(document.getElementById('title').textContent, /recientemente/);
  assert.match(document.getElementById('item-0').getAttribute('aria-label'), /Demo 1/);
  assert.match(document.getElementById('item-0').textContent, /Episodio 1/);
  click('item-0');
  assert.equal(pending[0].parameters.path, '/ver/demo-1');
  answer('<h1 class="anime-title">Demo 1</h1><script>var videos = [["Netu","https://hqq.tv/player/embed_player.php?vid=test"],["Other","https://video.example/embed/1"],["Netu","https://other.example/embed/1"]];</script>');
  click('item-0');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), true);
  click('player-mode');
  assert.equal(focused.id, 'cancel-compatibility');
  click('cancel-compatibility');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), true);
  click('player-mode');
  click('accept-compatibility');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), false);
  click('player-mode');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), true);
  assert.equal(document.getElementById('frame').hasAttribute('allowfullscreen'), false);
  click('close-player');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), true);
  click('item-1');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), true);
  click('close-player');
  click('item-2');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), true);
  click('close-player');
  click('directory');
  answer('<h1 class="title">Animes</h1><article class="anime"><a href="/anime/demo"><h3>Demo</h3></a></article><a rel="next" href="/directorio?p=2">Next</a>');
  assert.equal(document.getElementById('directory').getAttribute('aria-current'), 'page');
  assert.equal(document.getElementById('recent').hasAttribute('aria-current'), false);
  assert.equal(document.getElementById('pagination').hidden, false);
  assert.equal(document.getElementById('previous').disabled, true);
  click('next');
  assert.equal(pending[0].parameters.path, '/directorio?p=2');
  answer('<h1 class="title">Animes</h1><article class="anime"><a href="/anime/demo"><h3>Demo</h3></a></article><a rel="prev" href="/directorio?p=1">Previous</a>');
  assert.equal(document.getElementById('page-label').textContent, 'Página 2');
  assert.equal(document.getElementById('next').disabled, true);
  click('item-0');
  answer('<article class="anime-single"><h1 class="title">Demo</h1><p class="sinopsis">Synopsis</p></article><script>var anime_info = ["10","demo","Demo"]; var episodes = [2,1];</script>');
  assert.equal(document.getElementById('heading').hidden, true);
  assert.equal(document.getElementById('content-label').textContent, 'Episodios · 2');
  assert.equal(focused.id, 'continue-anime');
  assert.match(document.getElementById('continue-anime').textContent, /Episodio 1/);
  assert.equal(document.getElementById('item-1').classList.contains('last-opened'), true);
  click('continue-anime');
  assert.equal(pending[0].parameters.path, '/ver/demo-1');
  answer('<h1 class="anime-title">Demo 1</h1><script>var videos = [["Other","https://video.example/embed/1"]];</script>');
  assert.equal(document.getElementById('content-label').textContent, 'Servidores disponibles');
  click('item-0');
  assert.equal(document.getElementById('player-title').textContent, 'Demo 1');
  click('close-player');
  click('recent');
  assert.match(document.getElementById('remove-0').getAttribute('aria-label'), /Eliminar Demo/);
  click('clear-history');
  assert.equal(focused.id, 'cancel-clear');
  click('cancel-clear');
  assert.ok(document.getElementById('item-0'));
  click('remove-0');
  assert.equal(document.getElementById('item-0'), null);
  assert.equal(focused.id, 'recent');
  click('home');
  answer('<article class="episode"><a href="/ver/demo-1"><h3>Demo 1</h3></a></article>');
  click('item-0');
  answer('<h1 class="anime-title">Demo 1</h1><script>var videos = [["YourUpload","https://www.yourupload.com/embed/example"]];</script>');
  click('item-0');
  assert.equal(pending[0].method, 'probeProvider');
  assert.equal(document.getElementById('frame').hidden, true);
  pending.shift().onSuccess({ result: { statusCode: 404, unavailable: true } });
  assert.match(document.getElementById('player-notice-text').textContent, /HTTP 404/);
  assert.equal(document.getElementById('frame').getAttribute('src'), 'about:blank');
  click('choose-provider');
  assert.equal(document.getElementById('player').hidden, true);
  click('item-0');
  pending.shift().onSuccess({ result: { statusCode: 200, unavailable: false } });
  assert.equal(document.getElementById('frame').hidden, false);
  assert.equal(document.getElementById('frame').getAttribute('src'), 'https://www.yourupload.com/embed/example');
  click('close-player');
  click('item-0');
  click('close-player');
  pending.shift().onSuccess({ result: { statusCode: 200, unavailable: false } });
  assert.equal(document.getElementById('player').hidden, true);
  assert.equal(document.getElementById('frame').getAttribute('src'), 'about:blank');
  // El video directo no ejecuta la página del proveedor y conserva el mando.
  click('item-0');
  pending.shift().onSuccess({ result: { statusCode: 200, unavailable: false, streamUrl: 'http://127.0.0.1:45678/media/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa' } });
  assert.equal(video.hidden, false);
  assert.equal(video.getAttribute('src'), 'http://127.0.0.1:45678/media/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa');
  assert.equal(document.getElementById('frame').hidden, true);
  assert.equal(document.getElementById('native-controls').hidden, false);
  click('video-fullscreen');
  assert.equal(document.getElementById('player').classList.contains('video-expanded'), true);
  video.focus();
  const cursor = new window.Event('cursorStateChange'); cursor.detail = { visibility: false }; document.dispatchEvent(cursor);
  assert.notEqual(focused, video);
  assert.equal(document.getElementById('native-controls').contains(focused), true);
  key(461);
  assert.equal(document.getElementById('player').classList.contains('video-expanded'), false);
  assert.equal(document.getElementById('player').hidden, false);
  video.dispatchEvent(new window.Event('playing'));
  assert.match(document.getElementById('player-status').textContent, /Reproduciendo/);
  click('video-toggle');
  assert.equal(video.paused, true);
  video.currentTime = 20; video.duration = 120;
  click('video-forward');
  assert.equal(video.currentTime, 30);
  click('video-rewind');
  assert.equal(video.currentTime, 20);
  click('video-opening');
  assert.equal(video.currentTime, 105);
  click('video-opening');
  assert.equal(video.currentTime, 120);
  video.error = { code: 4 };
  video.dispatchEvent(new window.Event('error'));
  assert.match(document.getElementById('player-notice-text').textContent, /formato/);
  click('player-mode');
  pending.shift().onSuccess({ result: { statusCode: 200, unavailable: false, streamUrl: 'http://127.0.0.1:45678/media/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa' } });
  assert.equal(video.hidden, true);
  assert.equal(video.getAttribute('src'), null);
  assert.equal(document.getElementById('frame').hidden, false);
  click('close-player');
  // VOE utiliza HLS en el reproductor local, sin crear un iframe remoto.
  click('home');
  answer('<article class="episode"><a href="/ver/demo-1"><h3>Demo 1</h3></a></article>'); click('item-0');
  answer('<h1 class="anime-title">Demo 1</h1><div class="episodes-nav"><a href="/anime/demo">Listado</a><a href="/ver/demo-2">Episodio siguiente</a></div><script>var videos = [["Voe","https://voe.sx/e/example"]];</script>');
