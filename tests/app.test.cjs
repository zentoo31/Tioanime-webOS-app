const { test } = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const { parseHTML, DOMParser } = require('linkedom');
const { TioCatalog } = require('../app/catalog');
const { TioHistory } = require('../app/history');
test('app opens episodes and providers, closes playback, returns and retries', () => {
  const { window, document } = parseHTML(fs.readFileSync('app/index.html', 'utf8'));
  let focused;
  window.HTMLElement.prototype.focus = function () { focused = this; };
  Object.defineProperty(document, 'activeElement', { get: () => focused || document.body });
  const pending = [];
  const webOS = { service: { request: (uri, options) => pending.push(options) }, platformBack: () => {} };
  window.PalmSystem = {}; window.webOS = webOS;
  vm.runInNewContext(fs.readFileSync('app/main.js', 'utf8'), { window, document, webOS, DOMParser, TioCatalog, TioHistory, URL, setTimeout, clearTimeout, Error });
  function answer(html) { pending.shift().onSuccess({ html }); }
  function click(id) { document.getElementById(id).click(); }
  assert.equal(pending[0].parameters.path, '/');
  answer('<article class="episode"><a href="/ver/demo-1"><h3>Demo 1</h3></a></article>');
  assert.equal(focused.id, 'item-0');
  click('item-0');
  assert.equal(pending[0].parameters.path, '/ver/demo-1');
  answer('<h1 class="title">Demo 1</h1><script>var videos = [["Server","https://video.example/embed/1"]];</script>');
  click('item-0');
  assert.equal(document.getElementById('player').hidden, false);
  assert.equal(document.getElementById('frame').getAttribute('src'), 'https://video.example/embed/1');
  click('close-player');
  assert.equal(document.getElementById('frame').getAttribute('src'), 'about:blank');
  assert.equal(focused.id, 'item-0');
  click('back');
  assert.equal(pending[0].parameters.path, '/');
  answer('<article class="episode"><a href="/ver/demo-1"><h3>Demo 1</h3></a></article>');
  document.getElementById('query').value = 'one piece';
  document.getElementById('search').dispatchEvent(new window.Event('submit', { cancelable: true }));
  assert.equal(pending[0].parameters.path, '/directorio?q=one%20piece');
  pending.shift().onFailure({ errorText: 'Sin conexión' });
  assert.equal(document.getElementById('status').textContent, 'Sin conexión');
  assert.equal(document.getElementById('retry').hidden, false);
  click('retry'); answer('<h1 class="title">Resultados</h1>');
  assert.match(document.getElementById('status').textContent, /No se encontraron/);
  click('recent');
  assert.equal(pending.length, 0);
  assert.match(document.getElementById('title').textContent, /recientemente/);
  assert.match(document.getElementById('item-0').getAttribute('aria-label'), /Demo 1/);
  assert.match(document.getElementById('item-0').textContent, /Episodio 1/);
  click('item-0');
  assert.equal(pending[0].parameters.path, '/ver/demo-1');
  answer('<h1 class="anime-title">Demo 1</h1><script>var videos = [["Netu","https://hqq.tv/player/embed_player.php?vid=test"],["Other","https://video.example/embed/1"],["Netu","https://other.example/embed/1"]];</script>');
  click('item-0');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), false);
  click('close-player');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), false);
  click('item-1');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), false);
  click('close-player');
  click('item-2');
  assert.equal(document.getElementById('frame').hasAttribute('sandbox'), false);
  click('close-player');
  click('directory');
  answer('<h1 class="title">Animes</h1><article class="anime"><a href="/anime/demo"><h3>Demo</h3></a></article><a rel="next" href="/directorio?p=2">Next</a>');
  assert.equal(document.getElementById('directory').getAttribute('aria-current'), 'page');
  assert.equal(document.getElementById('recent').hasAttribute('aria-current'), false);
  assert.equal(document.getElementById('pagination').hidden, false);
  assert.equal(document.getElementById('previous').disabled, true);
  click('next');
  assert.equal(pending[0].parameters.path, '/directorio?p=2');
  answer('<h1 class="title">Animes</h1><article class="anime"><a href="/anime/demo"><h3>Demo</h3></a></article><a rel="prev" href="/directorio?p=1">Previous</a>');
  assert.equal(document.getElementById('page-label').textContent, 'Página 2');
  assert.equal(document.getElementById('next').disabled, true);
  click('item-0');
  answer('<article class="anime-single"><h1 class="title">Demo</h1><p class="sinopsis">Synopsis</p></article><script>var anime_info = ["10","demo","Demo"]; var episodes = [2,1];</script>');
  assert.equal(document.getElementById('heading').hidden, true);
  assert.equal(document.getElementById('content-label').textContent, 'Episodios · 2');
  assert.equal(focused.id, 'continue-anime');
  assert.match(document.getElementById('continue-anime').textContent, /Episodio 1/);
  assert.equal(document.getElementById('item-1').classList.contains('last-opened'), true);
  click('continue-anime');
  assert.equal(pending[0].parameters.path, '/ver/demo-1');
  answer('<h1 class="anime-title">Demo 1</h1><script>var videos = [["Other","https://video.example/embed/1"]];</script>');
  assert.equal(document.getElementById('content-label').textContent, 'Servidores disponibles');
  click('item-0');
  assert.equal(document.getElementById('player-title').textContent, 'Demo 1');
  click('close-player');
  click('recent');
  assert.match(document.getElementById('remove-0').getAttribute('aria-label'), /Eliminar Demo/);
  click('clear-history');
  assert.equal(focused.id, 'cancel-clear');
  click('cancel-clear');
  assert.ok(document.getElementById('item-0'));
  click('remove-0');
  assert.equal(document.getElementById('item-0'), null);
  assert.equal(focused.id, 'recent');
});

