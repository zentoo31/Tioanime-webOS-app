const { test } = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const { parseHTML, DOMParser } = require('linkedom');
const { TioCatalog } = require('../app/catalog');
const { JKCatalog } = require('../app/jkanime');
const { TioHistory } = require('../app/history');
test('search source switches only within search, JK navigation and history stay isolated', () => {
  const { window, document } = parseHTML(fs.readFileSync('app/index.html', 'utf8'));
  let focused, saved = '';
  window.HTMLElement.prototype.focus = function () { focused = this; };
  window.HTMLElement.prototype.blur = function () { if (focused === this) focused = document.body; };
  Object.defineProperty(document, 'activeElement', { get: () => focused || document.body });
  window.localStorage = { getItem: () => saved, setItem: (key, value) => { saved = value; } };
  const video = document.getElementById('native-video');
  video.pause = () => {}; video.load = () => {}; video.play = () => Promise.resolve();
  const pending = [];
  const webOS = { service: { request: (uri, options) => {
    if (options.method === 'holdPlayback') return { cancel() {} };
    if (options.method === 'images') { options.onSuccess({ assets: {} }); return; }
    pending.push(options);
  } }, platformBack() {} };
  window.webOS = webOS; window.PalmSystem = {};
  vm.runInNewContext(fs.readFileSync('app/main.js', 'utf8'), { window, document, webOS, DOMParser, TioCatalog, JKCatalog, TioHistory, URL, setTimeout, clearTimeout, Error });
  const $ = id => document.getElementById(id);
  const answer = html => pending.shift().onSuccess({ html });
  answer('<h1 class="title">Inicio</h1>');
  assert.equal($('source-switch').hidden, true);
  $('query').value = 'demo'; $('search').dispatchEvent(new window.Event('submit', { cancelable: true }));
  assert.equal(pending[0].parameters.path, '/directorio?q=demo');
  answer('<h1 class="title">Demo</h1>');
  $('source-jk').click();
  assert.equal(pending[0].parameters.path, '/jk/search?q=demo');
  answer({ html: '<div class="anime__item"><div data-setbg="https://cdn.jkdesa.com/assets/images/animes/image/demo.jpg"></div><h5><a href="https://jkanime.net/demo/">Demo</a></h5></div>' });
  assert.equal($('source-jk').getAttribute('aria-pressed'), 'true');
  assert.equal($('item-0').classList.contains('poster'), true);
  $('item-0').click();
  assert.equal(pending[0].parameters.path, '/jk/anime/demo');
  answer({ html: '<div class="anime_info"><h3>Demo</h3></div>', episodes: { current_page: 1, last_page: 2, total: 17, data: [{ number: 1 }] } });
  assert.equal($('source-switch').hidden, true);
  assert.equal($('pagination').hidden, false);
  $('next').click();
  assert.equal(pending[0].parameters.path, '/jk/anime/demo?p=2');
  answer({ html: '<div class="anime_info"><h3>Demo</h3></div>', episodes: { current_page: 2, last_page: 2, total: 17, data: [{ number: 17 }] } });
  $('item-0').click();
  assert.equal(pending[0].parameters.path, '/jk/ver/demo/17');
  answer({ html: '<a href="https://jkanime.net/demo/">Demo</a><a id="btn-show-0">Desu</a><script>video[0] = \'<iframe src="https://jkanime.net/jkplayer/um?e=test"></iframe>\';</script>' });
  $('item-0').click();
  assert.equal(pending[0].method, 'probeProvider');
  pending.shift().onSuccess({ result: { statusCode: 200, mediaType: 'application/vnd.apple.mpegurl', streamUrl: 'http://127.0.0.1:12345/resource/' + 'a'.repeat(48) + '/0' } });
  assert.equal(video.hidden, false);
  assert.match(video.getAttribute('src'), /resource/);
  $('close-player').click(); $('recent').click();
  assert.match($('item-0').textContent, /JKAnime/);
  assert.match(saved, /\/jk\/ver\/demo\/17/);
  $('recent-catalog-0').click();
  assert.equal(pending[0].parameters.path, '/jk/anime/demo');
  answer({ html: '<div class="anime_info"><h3>Demo</h3></div>', episodes: { data: [{ number: 1 }], current_page: 1, last_page: 2, total: 17 } });
  assert.match($('continue-anime').textContent, /17/);
  $('home').click(); answer('<h1 class="title">Inicio</h1>');
  $('query').value = 'demo'; $('search').dispatchEvent(new window.Event('submit', { cancelable: true }));
  assert.equal(pending[0].parameters.path, '/directorio?q=demo'); answer('<h1 class="title">Demo</h1>');
});
